//! Authored source-action correspondence without current schema or role seals.
use super::*;

/// Source evidence and exact action correspondence are preserved independently of
/// the definitions and roles against which the final adapter will be checked.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case", deny_unknown_fields)]
pub enum SourceActionCorrespondenceContent {
    PobPhysicalPrimaryStatSetsV1 {
        source: SourcePin,
        catalog: OwnedContentDigest,
        gem: GemDefId,
        game_id: String,
        variant_id: String,
        skill_id: String,
        name_spec: String,
        primary: SkillDefId,
        primary_supply: DeclaredSlot<SkillGrantSlotDefId>,
        entering_grant: DeclaredSlot<GrantSlotDefId>,
        output: DeclaredSlot<ActionOutputDefId>,
        part: ActionPartDefId,
        mode: ActionModeDefId,
        stat_sets: Vec<SourceStatSetMapping>,
        absent_stat_set: Option<ActionStatSetDefId>,
        index: ValueRecipeInput,
    },
    PobPhysicalSingletonMinionActionsV1 {
        source: SourcePin,
        catalog: OwnedContentDigest,
        gem: GemDefId,
        game_id: String,
        variant_id: String,
        skill_id: String,
        name_spec: String,
        primary: SkillDefId,
        primary_supply: DeclaredSlot<SkillGrantSlotDefId>,
        entering_grant: DeclaredSlot<GrantSlotDefId>,
        minion: SourceSingletonMinion,
        actions: Vec<SourceMinionActionMapping>,
        absent_action: Option<u32>,
        main_action_index: Box<ValueRecipeInput>,
        calcs_action_index: Box<ValueRecipeInput>,
        map_skill_index: Box<ValueRecipeInput>,
        map_stat_set_index: ValueRecipeInput,
    },
    PobManualDirectSingletonMinionActionsV1 {
        source: SourcePin,
        catalog: OwnedContentDigest,
        catalog_gem: GemDefId,
        game_id: String,
        variant_id: String,
        skill_id: String,
        name_spec: String,
        skill: SkillDefId,
        manual_sources: Vec<SourceComponent>,
        minion: SourceSingletonMinion,
        actions: Vec<SourceMinionActionMapping>,
        absent_action: Option<u32>,
        main_action_index: Box<ValueRecipeInput>,
        calcs_action_index: Box<ValueRecipeInput>,
        map_skill_index: Box<ValueRecipeInput>,
        map_stat_set_index: ValueRecipeInput,
    },
}

