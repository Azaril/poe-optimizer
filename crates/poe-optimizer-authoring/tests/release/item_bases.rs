// Test-only projections of the pinned evidence keep these laws independent of
// the retired publication command and its converter-specific DTOs.
#[derive(Deserialize)]
struct Catalog {
    bases: Vec<Base>,
}
#[derive(Deserialize)]
struct Base {
    name: String,
    weapon_field: WeaponField,
}
#[derive(Deserialize)]
#[serde(rename_all = "snake_case")]
enum WeaponField {
    Table,
    Absent,
}
#[derive(Deserialize)]
struct Policy {
    catalog_sha256: String,
    capability: CapabilityDefId,
    templates: Vec<Template>,
}
#[derive(Deserialize)]
struct Template {
    source_base: String,
    template: ItemTemplateDefId,
}

fn source() -> (Catalog, Policy) {
    let root =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../../data/owned/poe2/3887ae68/item-bases");
    let catalog = fs::read(root.join("catalog.json")).unwrap();
    let policy = fs::read(root.join("policy.json")).unwrap();
    // These independent source and identity inventories are not regenerated by
    // the release builder under test.
    let catalog_hash = format!("{:x}", Sha256::digest(&catalog));
    assert_eq!(
        catalog_hash,
        "6dda4b5aa9371050b72343542219ad54d6b469ce16af7ede3c0e9cacbbec9554"
    );
    assert_eq!(
        format!("{:x}", Sha256::digest(&policy)),
        "8a2880b1ce37c6d89396436f90b1a9b7897dba75ae1b161044a617142a506e81"
    );
    let policy: Policy = serde_json::from_slice(&policy).unwrap();
    assert_eq!(policy.catalog_sha256, catalog_hash);
    let catalog: Catalog = serde_json::from_slice(&catalog).unwrap();
    assert_eq!(catalog.bases.len(), 1756);
    assert_eq!(policy.templates.len(), 1756);
    assert_eq!(policy.capability.key().as_str(), "def.0000000000001d3b");
    (catalog, policy)
}

fn selector(name: &str) -> ExternalSelector {
    ExternalSelector::Definition(ExternalOwnerSelector::ItemTemplate {
        base: SourceComponent::Text(name.into()),
        prototype: SourceComponent::Missing,
        variant: SourceComponent::Missing,
    })
}

#[test]
fn complete_base_catalog_retains_exact_template_identities_and_partial_rule_owners() {
    let (catalog, policy) = source();
    let release = tracked_release().release();
    let recipe = release.assembled().checked();
    let names: BTreeSet<_> = catalog.bases.iter().map(|row| &row.name).collect();
    let bindings: BTreeSet<_> = policy
        .templates
        .iter()
        .map(|row| &row.source_base)
        .collect();
    assert_eq!(names.len(), 1756);
    assert_eq!(names, bindings);
    let mut identities = BTreeSet::new();
    for binding in &policy.templates {
        assert!(identities.insert(binding.template.clone()));
        let owner = SchemaSubject::Definition(binding.template.address());
        assert_eq!(
            release.mapping().lookup(&selector(&binding.source_base)),
            Some(&MappingOutcome::Mapped {
                target: owner.clone(),
                basis: MappingBasis::Exact,
            })
        );
        let DefinitionDescriptor::ItemTemplate(template) = recipe
            .schema()
            .lookup_definition(&binding.template.address())
            .unwrap()
        else {
            panic!("exact typed ItemTemplate descriptor")
        };
        assert_eq!(template.id, binding.template);
        assert!(matches!(template.schema, SchemaState::Known(_)));
        let owners: Vec<_> = recipe
            .rules()
            .input()
            .owners
            .iter()
            .filter(|row| row.owner == owner)
            .collect();
        let [rules] = owners.as_slice() else {
            panic!("one rule owner per template")
        };
        let SchemaClosure::Partial { gaps } = &rules.programs.closure else {
            panic!("profile presence must not establish complete item mechanics")
        };
        assert!(!gaps.is_empty());
        assert!(gaps.iter().all(|gap| gap.subject == owner));
    }
    let DefinitionDescriptor::Capability(capability) = recipe
        .schema()
        .lookup_definition(&policy.capability.address())
        .unwrap()
    else {
        panic!("typed capability")
    };
    let SchemaState::Known(schema) = &capability.schema else {
        panic!("known capability targets")
    };
    assert_eq!(schema.targets, [RuleEntityKind::EquipmentUse]);
}

#[test]
fn every_base_profile_presence_uses_the_exact_equipment_capability_and_replays() {
    let (catalog, policy) = source();
    let recipe = tracked_release().release().assembled().checked();
    let compiled = recipe.compiled_rules();
    let mut scratch = compiled.new_scratch();
    for reverse in [false, true] {
        let mut bindings: Vec<_> = policy.templates.iter().collect();
        if reverse {
            bindings.reverse();
        }
        let mut counts = [0; 2];
        for binding in bindings {
            let row = catalog
                .bases
                .iter()
                .find(|row| row.name == binding.source_base)
                .unwrap();
            let expected = match row.weapon_field {
                WeaponField::Table => true,
                WeaponField::Absent => false,
            };
            let owner = SchemaSubject::Definition(binding.template.address());
            let rules = recipe
                .rules()
                .input()
                .owners
                .iter()
                .find(|row| row.owner == owner)
                .unwrap();
            let programs: Vec<_> = rules
                .programs
                .members
                .iter()
                .filter(|program| {
                    program.effects.iter().any(|effect| {
                        matches!(
                            &effect.effect,
                            RuleEffectKind::Capability { capability, .. }
                                if capability == &policy.capability
                        )
                    })
                })
                .collect();
            let [program] = programs.as_slice() else {
                panic!("exactly one profile-source capability program")
            };
            assert_eq!(program.id.as_str(), "template-supplies-base-attack-profile");
            assert_eq!(program.context, RuleEntityKind::EquipmentUse);
            assert!(program.reads.is_empty());
            let [node] = program.nodes.as_slice() else {
                panic!("one source-presence value")
            };
            assert_eq!(
                node.expression,
                RuleExpression::Literal {
                    value: ParameterValue::Boolean(expected),
                }
            );
            let [effect] = program.effects.as_slice() else {
                panic!("one source-presence effect")
            };
            assert_eq!(effect.id.as_str(), "base-attack-profile-source");
            assert!(effect.when.is_none());
            assert_eq!(
                effect.effect,
                RuleEffectKind::Capability {
                    entity: RuleEntity::Current,
                    capability: policy.capability.clone(),
                    enabled: node.id.clone(),
                }
            );
            let fresh = compiled
                .evaluate(
                    &owner,
                    &program.id,
                    &[],
                    recipe.schema().as_ref(),
                    &mut compiled.new_scratch(),
                )
                .unwrap();
            let reused = compiled
                .evaluate(
                    &owner,
                    &program.id,
                    &[],
                    recipe.schema().as_ref(),
                    &mut scratch,
                )
                .unwrap();
            assert_eq!(fresh, reused);
            assert_eq!(reused.owner, owner);
            assert_eq!(reused.owner_programs_closure, rules.programs.closure);
            let [actual] = reused.effects.as_slice() else {
                panic!("one applied capability fact")
            };
            assert_eq!(actual.id, effect.id);
            assert_eq!(actual.effect, effect.effect);
            assert_eq!(
                actual.disposition,
                EffectDisposition::Applied {
                    value: ParameterValue::Boolean(expected),
                }
            );
            match binding.source_base.as_str() {
                "Grand Spear" | "Sinister Quarterstaff" => assert!(expected),
                "Rattling Sceptre" | "Shrine Sceptre" | "Ashen Staff" | "Sapphire Ring" => {
                    assert!(!expected)
                }
                _ => {}
            }
            counts[usize::from(expected)] += 1;
        }
        assert_eq!(counts, [1419, 337]);
    }
}

#[test]
fn five_originals_retain_their_base_template_identities_on_the_current_release() {
    let (_, policy) = source();
    let release = tracked_release().release();
    let recipe = release.assembled().checked();
    let templates: BTreeSet<_> = policy.templates.iter().map(|row| &row.template).collect();
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    for (index, (known, base)) in [
        (13, "Rattling Sceptre"),
        (28, "Grand Spear"),
        (16, "Sinister Quarterstaff"),
        (19, "Ashen Staff"),
        (25, "Ashen Staff"),
    ]
    .into_iter()
    .enumerate()
    {
        let case = index + 1;
        let xml = fs::read(root.join(format!(
            "tests/fixtures/builds/breadth-20260908/build-{case:02}.xml"
        )))
        .unwrap();
        let imported = ImportedBuildInstance::from_decoded(
            decode_build(&xml).unwrap(),
            BuildLineage::from_bytes([case as u8; 16]),
            Default::default(),
        )
        .unwrap();
        let evidence = SourceProjectEvidence::collect(&imported, Default::default()).unwrap();
        let query_set = release
            .query_sets()
            .iter()
            .find(|set| set.name.as_str() == format!("original-{case:02}"))
            .unwrap();
        let normalized = normalize_fresh(
            &evidence,
            *imported.allocator_state(),
            NormalizationArtifacts {
                mappings: release.mapping(),
                registry: recipe.registry(),
                definitions: recipe.schema().as_ref(),
                roles: release.roles(),
                rewards: release.rewards(),
                items: release.items(),
                item_source: release.item_source(),
                tree: release.tree(),
            },
            release.normalization(),
            &query_set.queries,
            Default::default(),
        )
        .unwrap();
        let actual: Vec<_> = normalized
            .draft()
            .input()
            .items
            .members
            .iter()
            .filter_map(|item| match &item.template {
                DraftField::Known { value } => Some(value),
                _ => None,
            })
            .collect();
        assert_eq!(actual.len(), known, "original {case}");
        assert!(actual.iter().all(|template| templates.contains(template)));
        let expected = &policy
            .templates
            .iter()
            .find(|binding| binding.source_base == base)
            .unwrap()
            .template;
        assert!(actual.contains(&expected), "original {case}: {base}");
        // The maintained originals test checks the current selected Pending
        // obligations and query provenance. Do not restore historical all-item
        // or all-allocation Pending assertions after independent progress.
    }
}
